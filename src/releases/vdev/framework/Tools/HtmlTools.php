            'animation' => $animation,
            'filter' => $filter,
            'backdrop-filter' => $backdropFilter,
        ];

        foreach ($additionalProperties as $property => $value) {
            if (!is_string($property) || !is_string($value)) {
                continue;
            }

            $css = str_starts_with($property, '--')
                ? $property
                : strtolower((string) preg_replace('/([a-z0-9])([A-Z])/', '$1-$2', $property));

            if (preg_match('/^(?:--[A-Za-z0-9_-]+|(?:-(?:webkit|moz|ms|o)-)?[a-z][a-z0-9-]*)$/', $css) === 1) {
                $items[$css] = $value;
            }
        }

        $styles = [];
        foreach ($items as $css => $value) {
            if ($value !== null && trim($value) !== '') {
                $styles[] = $css . ':' . $value . ';';
            }
        }

        return $styles === [] ? '' : ' style="' . implode(';', $styles) . ';" ';
    }

